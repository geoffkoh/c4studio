// Regenerates `src/glyphWidths.ts`: the advance width of each character in
// the Studio's font, at each size and weight the headless renderer draws.
//
// The renderer has no DOM, so it cannot measure text; it used to guess a
// flat 0.55 em per character, which runs 8–26% wide and broke lines well
// before the canvas does (PP-223). Measured per size, not once and scaled:
// the system font changes its letter spacing at small sizes, and a table
// taken at 100px came out 13% narrow at 10px.
//
// Run from the repo root, in the conda env that has Node:
//   conda run -n pystructurizr --no-capture-output \
//     node packages/diagram-core/scripts/measure-glyphs.mjs
//
// It measures with whatever font the machine resolves the stack to, so run
// it where the diagrams are viewed. The committed table is macOS's SF Pro.

import { writeFileSync } from "node:fs";

import { chromium } from "playwright";

const FONT = `-apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, Helvetica, Arial, sans-serif`;
const SIZES = [
  [10, 400],
  [11, 400],
  [12, 600],
  [13, 600],
  [18, 600],
];
const CHARS = [
  ...Array.from({ length: 95 }, (_, i) => String.fromCharCode(32 + i)),
  ..."–—‘’“”…·•×é",
].join("");
const RUN = 40;

const browser = await chromium.launch();
const page = await browser.newPage();
await page.setContent(
  `<div id="m" style='font-family:${FONT};white-space:pre;position:absolute'></div>`,
);
const tables = {};
for (const [size, weight] of SIZES) {
  tables[`${size}/${weight}`] = await page.evaluate(
    ({ chars, size, weight, run }) => {
      const m = document.getElementById("m");
      m.style.fontSize = `${size}px`;
      m.style.fontWeight = String(weight);
      return [...chars].map((ch) => {
        // A run of one character, so its advance is measured to well under
        // a pixel; stored per pixel of font size.
        m.textContent = ch.repeat(run);
        return Math.round((m.getBoundingClientRect().width / run / size) * 10000) / 10000;
      });
    },
    { chars: CHARS, size, weight, run: RUN },
  );
}
await browser.close();

const rows = Object.entries(tables)
  .map(([key, widths]) => `  "${key}": [${widths.join(", ")}],`)
  .join("\n");
const source = `// Generated by scripts/measure-glyphs.mjs — do not edit by hand (PP-223).
//
// Advance width of each character in GLYPH_CHARS, per pixel of font size,
// keyed by "size/weight": the Studio's font, measured in Chromium.

export const GLYPH_CHARS = ${JSON.stringify(CHARS)};

export const GLYPH_WIDTHS: Record<string, readonly number[]> = {
${rows}
};
`;
const target = new URL("../src/glyphWidths.ts", import.meta.url);
writeFileSync(target, source);
console.log(`wrote ${target.pathname}`);
